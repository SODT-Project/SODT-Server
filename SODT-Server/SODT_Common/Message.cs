			FileHash = fileHash;
		}
		public static Transfer CreateRequest(string fileName, long fileSize, byte[] fileHash)
		{
			return new Transfer(PacketCode.Request, fileName, fileSize, fileHash);
		}
		public static Transfer CreateResponse(Transfer request)
		{
			// keep the same UUID
			return new Transfer(
				request.Uuid,
