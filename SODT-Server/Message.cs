	public enum PacketCode
	{
		/// <summary>
		/// Request packet code, typically sent by clients to initiate a connection or request data transfer.
		/// </summary>
		Request = 100,

		/// <summary>
		/// OK packet code, indicating a successful response from the server or the completion of an operation.
		/// </summary>
		Ok = 200,

		/// <summary>
		/// Denied packet code, indicating that a request cannot be fulfilled due to errors or restrictions.
		/// </summary>
		Denied = 300,

		/// <summary>
		/// Error packet code, used to report any issues encountered during the execution of an operation.
		/// </summary>
		Error = 400
	}
	public static class MessageHelper
	{
		public const int FullMessageSize = 4096;

		public const int NonceSize = 12;

		public const int TagSize = 16; // 16 is the maximum tag size for AES-GCM

		public const int ContentLengthSize = 2;

		public const int IdSize = 2;
		
		public const int HeaderSize = NonceSize + TagSize + ContentLengthSize + IdSize;
		
		/// <summary>
		/// The total size of the message content plus 2 bytes that define the inner content size.
		/// </summary>
		public const int MessageWithHeaders = FullMessageSize - IdSize;
		/// <summary>
		/// The maximum size of the message content, excluding the content length header and source/target IDs.
		/// Note that additional bytes generated by the ToJson() method may increase the overall size of the packet.
		/// However, the final size must still be less or equal to 4092 bytes.
		/// </summary>
		public const int MessageContentSize = FullMessageSize - HeaderSize;
		public static byte[] ToBytes(IBaseMessage baseMessage)
		{
			//get content 
			byte[] content = Encoding.UTF8.GetBytes(baseMessage.ToJson());

			//check if content is too large																  
			if (content.Length > MessageContentSize)
			{
				throw new ArgumentException("Message size is too large");
			}
			//create byte array
			byte[] contentLength = BitConverter.GetBytes((ushort)content.Length); //contentLength is always 2 bytes because it's convertet to ushort
			byte[] bytes = new byte[MessageWithHeaders];
			bytes[0] = contentLength[0];
			bytes[1] = contentLength[1];
			Array.Copy(content, 0, bytes, 2, content.Length);
			return bytes;
		}
	}
	/// <summary>
	/// Represents a base interface for all messages in the system. This class serves as a foundation 
	/// for creating other message types that inherit its properties and functionality.
	/// </summary>
	/// <remarks>This interface is designed to be extended by other message classes.</remarks>
	public interface IBaseMessage
	{
		/// <summary>
		/// Gets or sets the unique identifier for this message, used to distinguish it from others.
		/// </summary>
		[JsonPropertyName("uuid")]
		public int Uuid { get; set; }

		/// <summary>
		/// Gets or sets the code of the message, representing its type and purpose.
		/// </summary>
		[JsonPropertyName("code")]
		public int Code { get; set; }

		/// <summary>
		/// Gets or sets the type of the message, used to categorize it according to its functionality.
		/// </summary>
		[JsonPropertyName("type")]
		public string Type { get; set; }

		/// <summary>
		/// Converts the message to a JSON string.
		/// </summary>
		/// <returns>The JSON representation of the message.</returns>
		public string ToJson();
		/// <summary>
		/// Converts the message to a json string and then to a byte array.
		/// </summary>
		/// <returns>The byte array representation of the json string of this message.</returns>
		public byte[] ToBytes();
	}

	/// <summary>
	/// Represents a base message in the system. This struct provides the basic properties that all messages
	/// inherit and use to communicate with other components in the system. It is a direct implementation of IBaseMessage.
	/// </summary>
	public struct BaseMessage : IBaseMessage
	{
		[JsonPropertyName("uuid")]
		public int Uuid { get; set; }

		[JsonPropertyName("code")]
		public int Code { get; set; }

		[JsonPropertyName("type")]
		public string Type { get; set; }

		//default BaseMessage constructor should not be overriden to avoid parsing errors

		public string ToJson()
		{
			return JsonSerializer.Serialize(this);
		}
		public byte[] ToBytes()
		{
			return MessageHelper.ToBytes(this);
		}
	}

	/// <summary>
	/// Represents a discovery message in the system. This struct inherits from BaseMessage and provides 
	/// additional properties relevant to discovery operations.
	/// </summary>
	/// <remarks>This class is designed for use in scenarios where clients need to discover available services or nodes.</remarks>
	public struct Discovery : IBaseMessage
	{
		[JsonPropertyName("uuid")]
		public int Uuid { get; set; }

		[JsonPropertyName("code")]
		public int Code { get; set; }

		[JsonPropertyName("type")]
		public string Type { get; set; }

		[JsonPropertyName("key")]
		public byte[]? Key { get; set; }

		[JsonPropertyName("iv")]
		public byte[]? Iv { get; set; }

		/// <summary>
		/// Contains the id of a client assigned by the server.
		/// </summary>
		[JsonPropertyName("id")]
		public byte Id { get; set; }
		/// <summary>
		/// Generate a new discovery message with the specified properties and new UUID.
		/// </summary>
		/// <param name="code"></param>
		/// <param name="id">Contains the id of a client assigned by the server</param>
		private Discovery(PacketCode code, byte assignedId, byte[]? key, byte[]? iv)
		{
			Uuid = new Random().Next();
			Code = (int)code;
			Type = "discovery";
			Id = assignedId;
			Key = key;
			Iv = iv;
		}

		public static Discovery CreateRequest(byte[] key, byte[] iv, RSA serverPublicKey)
		{
			return new Discovery(PacketCode.Request, 0, key, iv);
		}
		public static Discovery CreateResponse(byte assignedId)
		{
			return new Discovery(PacketCode.Ok, assignedId, null, null);
		}
		public string ToJson()
		{
			return JsonSerializer.Serialize(this);
		}
		public byte[] ToBytes()
		{
			return MessageHelper.ToBytes(this);
		}

		/// <summary>
		/// Converts the message to a byte array and encrypts it using the specified server public key.
		/// Encrypted message has following structure:
		/// <code>[ encLengthByte0, encLengthByte1, encByte0, encByte1, ..., encByte512, 0, 0, ..., 0]</code>
		/// EncLength is the length of the encrypted message in two bytes.
		/// </summary>
		/// <param name="serverPublicKey"></param>
		/// <returns></returns>
		/// <exception cref="ArgumentException"></exception>
		public byte[] ToEncryptedBytes(RSA serverPublicKey)
		{
			byte[] content = Encoding.UTF8.GetBytes(this.ToJson());
			if (content.Length > MessageHelper.MessageContentSize)
			{
				throw new ArgumentException("Message size is too large");
			}

			//contentLength is always 2 bytes because it's convertet to ushort
			byte[] contentLength = BitConverter.GetBytes((ushort)content.Length);
			//encrypt the content including the content length
			byte[] rsaEncrypted = serverPublicKey.Encrypt([contentLength[0], contentLength[1], .. content], RSAEncryptionPadding.Pkcs1);
			//resulting rsaEncrypted is always 512 bytes because of the 4096-bit RSA key encryption
			byte[] bytes = new byte[MessageHelper.MessageWithHeaders];
			//fill bytes with random data for obfuscation
			new Random().NextBytes(bytes);
			Array.Copy(rsaEncrypted, 0, bytes, 0, rsaEncrypted.Length);
			return bytes;
		}
	}

	/// <summary>
	/// Represents a key exchange message in the system. This class inherits from BaseMessage and provides 
	/// additional properties relevant to key exchange operations.
	/// </summary>
	/// <remarks>This class is designed for use in scenarios where clients need to establish secure connections.</remarks>
	public struct KeyExchange : IBaseMessage
	{
		/// <summary>
		/// Gets or sets the unique identifier for this message, used to distinguish it from others.
		/// </summary>
		[JsonPropertyName("uuid")]
		public int Uuid { get; set; }

		/// <summary>
		/// Gets or sets the code of the message, representing its type and purpose.
		/// </summary>
		[JsonPropertyName("code")]
		public int Code { get; set; }

		/// <summary>
		/// Gets or sets the type of the message, used to categorize it according to its functionality.
		/// </summary>
		[JsonPropertyName("type")]
		public string Type { get; set; }


		/// <summary>
		/// Gets or sets the shared secret key used for encryption.
		/// </summary>
		[JsonPropertyName("key")]
		public byte[] Key { get; set; }

		/// <summary>
		/// Gets or sets the session hash used to verify the integrity of the key exchange.
		/// </summary>
		[JsonPropertyName("sessionHash")]
		public byte[]? SessionHash { get; set; }

		/// <summary>
		/// Gets or sets the source clientId for the key exchange.
		/// </summary>
		[JsonPropertyName("sourceId")]
		public byte SourceId { get; set; }

		/// <summary>
		/// Gets or sets the target clientId for the key exchange.
		/// </summary>
		[JsonPropertyName("targetId")]
		public byte TargetId { get; set; }

		/// <summary>
		/// Generate a new key exchange message with the specified properties and new UUID.
		/// </summary>
		/// <param name="code"></param>
		/// <param name="key"></param>
		/// <param name="sessionHash"></param>
		/// <param name="targetId">Target clientId for the key exchange.</param>
		private KeyExchange(PacketCode code, byte[] key, byte[]? sessionHash, byte sourceId, byte targetId)
		{
			Uuid = new Random().Next();
			Code = (int)code;
			Type = "exchange";
			Key = key;
			SessionHash = sessionHash;
			SourceId = sourceId;
			TargetId = targetId;
		}

		public static KeyExchange Create(PacketCode code, byte[] key, byte[]? sessionHash, byte sourceId, byte targetId)
		{
			return new KeyExchange(code, key, sessionHash, sourceId, targetId);
		}
		public static KeyExchange CreateError(KeyExchange keyExchange)
		{
			keyExchange.Code = (int)PacketCode.Error;
			//switch source and target id
			(keyExchange.TargetId, keyExchange.SourceId) = (keyExchange.SourceId, keyExchange.TargetId);
			return keyExchange;
		}
		public string ToJson()
		{
			return JsonSerializer.Serialize(this);
		}
		public byte[] ToBytes()
		{
			return MessageHelper.ToBytes(this);
		}
	}

